void GigabyteGhostController::Flush(hid_device* dev)
{
    if(!dev) return;
    unsigned char buf[GIGABYTE_GHOST_REPORT_SIZE] = { 0 };
    hid_get_feature_report(dev, buf, GIGABYTE_GHOST_REPORT_SIZE);
}

bool GigabyteGhostController::SendFeatureReport(hid_device* dev, const unsigned char* data, size_t size)
{
    if(!dev || size < 8) return false;

    unsigned char packet[GIGABYTE_GHOST_REPORT_SIZE];
    packet[0] = 0x00; // Report ID
    for(size_t i = 0; i < 8; i++)
    {
        packet[i + 1] = data[i];
    }

    Flush(dev);
    int res = hid_send_feature_report(dev, packet, sizeof(packet));
    Flush(dev);

    return (res >= 0);
}

void GigabyteGhostController::UnlockDevice(hid_device* dev)
{
    if(!dev) return;

    for(size_t i = 0; i < 130; i++)
    {
        SendFeatureReport(dev, GHOST_INIT_PACKETS[i], 8);
        std::this_thread::sleep_for(std::chrono::milliseconds(5));
    }
    std::this_thread::sleep_for(std::chrono::milliseconds(500));
}

void GigabyteGhostController::SetAllProfileColors(unsigned char* r, unsigned char* g, unsigned char* b)
{
    /* Mutex prevents concurrent updates from GUI/Effects engine */
    std::lock_guard<std::mutex> lock(update_mutex);

    bool needs_update = false;
    bool changed[3] = { false, false, false };

    for(int i = 0; i < 3; i++)
    {
        if(first_update || r[i] != last_r[i] || g[i] != last_g[i] || b[i] != last_b[i])
        {
            changed[i] = true;
            needs_update = true;
            last_r[i] = r[i];
            last_g[i] = g[i];
            last_b[i] = b[i];
        }
    }

    if(!needs_update)
    {
        return; /* Nothing changed, do not overwhelm the mouse! */
    }

    first_update = false;

    /* Open a fresh handle for every update, just like GHOST_Color_Tool.py */
    hid_device* dev = hid_open_path(hid_path.c_str());
    if(!dev) return;

    for(unsigned char i = 0; i < 3; i++)
    {
        if(!changed[i]) continue; /* Skip profiles that haven't changed */

        unsigned char profile_cmd[8] = { 0x01, 0x88, i, 0x00, 0x00, 0x00, 0x00, 0x12 };
        SendFeatureReport(dev, profile_cmd, 8);

        std::this_thread::sleep_for(std::chrono::milliseconds(500));

        unsigned char color_cmd[8] = { 0x01, 0x86, i, r[i], g[i], b[i], 0x02, 0x00 };
        SendFeatureReport(dev, color_cmd, 8);

        std::this_thread::sleep_for(std::chrono::milliseconds(500));
    }

    /* Switch back to profile 0 to leave the mouse in a consistent state */
    unsigned char reset_cmd[8] = { 0x01, 0x88, 0x00, 0x00, 0x00, 0x00, 0x00, 0x12 };
    SendFeatureReport(dev, reset_cmd, 8);

    /* Allow the mouse time to process the reset before the next possible update */
    std::this_thread::sleep_for(std::chrono::milliseconds(500));

    /* Close immediately so the device is free again */
    hid_close(dev);
}

